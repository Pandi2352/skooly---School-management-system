export const readSampleTemplates = () => templates

/** Saving a custom design updates it; saving from a starter (or a blank design) adds a new one. */
export function saveSampleTemplate(id: string | null, draft: TemplateDraft, now: Date): Template {
  const existing =
    id === null
      ? undefined
      : templates.find((template) => template.id === id && template.source === 'custom')
  const saved: Template = {
    ...draft,
    id: existing?.id ?? `design-${now.getTime()}`,
    source: 'custom',
    updatedAt: now.toISOString(),
  }
  templates = existing
    ? templates.map((template) => (template.id === saved.id ? saved : template))
    : [saved, ...templates]
  return saved
}
